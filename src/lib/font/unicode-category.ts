/**
 * Unicode general categories, resolved from the code point ranges that
 * constitute each category.
 *
 * This is deliberately range-based rather than a full UCD table: it is used to
 * group glyphs for browsing, where the coarse distinction between a letter, a
 * digit, a mark and a symbol is what matters. It is never used to assert
 * anything about a specific code point beyond that grouping.
 */

export type GlyphCategory =
  | "letter"
  | "number"
  | "punctuation"
  | "symbol"
  | "mark"
  | "separator"
  | "control"
  | "unassigned";

